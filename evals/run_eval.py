"""Live evaluation harness.

Pipeline position: the quality gate. It asks every dataset question through the real pipeline
and reports strictness (leaks), usefulness (false refusals), grounding (sources, must_include),
and the similarity score distributions used to calibrate `SIMILARITY_THRESHOLD`.

    uv run python -m evals.run_eval --dataset evals/dataset.yaml --repeats 1 --kb synthetic

`--kb synthetic` (default) ingests the fictional persona into a temporary directory and never
touches the real index. `--kb real` uses the existing index with a personal dataset
(`evals/personal_dataset.yaml`, gitignored). This module makes live OpenAI calls and costs money;
it prints the call estimate and asks for confirmation unless `--yes` is given.
"""

import argparse
import logging
import sys
import tempfile
import time
from collections.abc import Callable
from datetime import datetime
from pathlib import Path

from evals import metrics
from evals.cases import CaseRun, DatasetError, EvalCase, load_cases
from evals.report import RunMeta, render_report, render_summary
from personal_rag.config import ConfigError, Settings, load_settings
from personal_rag.llm.client import UpstreamError
from personal_rag.query.pipeline import InvalidQuestionError, QueryPipeline
from personal_rag.schemas import AskResponse
from personal_rag.services import Services, build_services
from personal_rag.store.vector_store import IndexMismatchError

DEFAULT_DATASET = Path("evals/dataset.yaml")
PERSONAL_DATASET = Path("evals/personal_dataset.yaml")
REPORT_DIR = Path("evals/reports")
# The committed persona (generated by tests/fixtures/make_fixtures.py). Read as plain files so
# the harness does not import from the test tree.
PERSONA_DIR = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "persona"
PERSONA_FILES = ("cv.md", "projects.txt", "certifications.docx", "cv_onepage.pdf")

logger = logging.getLogger(__name__)


def to_case_run(case: EvalCase, run: int, response: AskResponse, latency_ms: float) -> CaseRun:
    debug = response.debug
    return CaseRun(
        case=case,
        run=run,
        status=response.status,
        answer=response.answer,
        source_files=[s.filename for s in response.sources],
        classifier_category=debug.classifier_category if debug else None,
        classifier_reason=debug.classifier_reason if debug else None,
        scores=[(h.similarity, h.kept) for h in debug.retrieved] if debug else [],
        latency_ms=latency_ms,
        usage=dict(debug.token_usage) if debug else {},
    )


def run_cases(
    cases: list[EvalCase],
    pipeline: QueryPipeline,
    repeats: int,
    progress: Callable[[str], None] = lambda _: None,
) -> list[CaseRun]:
    """Ask every case `repeats` times.

    A question the pipeline rejects as invalid is recorded as `invalid_input`. An unusable index
    (IndexMismatchError) is not recoverable per case, so it propagates and aborts the run.
    """
    runs: list[CaseRun] = []
    for repeat in range(repeats):
        for index, case in enumerate(cases, start=1):
            started = time.perf_counter()
            try:
                response = pipeline.ask(case.question, debug=True)
            except InvalidQuestionError:
                logger.warning("case %s was rejected as an invalid question", case.id)
                runs.append(CaseRun(case=case, run=repeat, status="invalid_input", answer=""))
                progress(
                    f"run {repeat + 1}/{repeats}  {index}/{len(cases)}  {case.id}: invalid_input"
                )
                continue
            latency = (time.perf_counter() - started) * 1000
            runs.append(to_case_run(case, repeat, response, latency))
            position = f"run {repeat + 1}/{repeats}  {index}/{len(cases)}"
            progress(f"{position}  {case.id}: {response.status}")
    return runs


def estimate_calls(case_count: int, repeats: int, groundedness: bool) -> tuple[int, int]:
    """(minimum, maximum) API calls: one classifier call, up to embed + generate (+ check)."""
    per_case_max = 3 + (1 if groundedness else 0)
    return case_count * repeats, case_count * repeats * per_case_max


def prepare_persona(directory: Path) -> list[Path]:
    """Copy the four persona files into `directory`."""
    directory.mkdir(parents=True, exist_ok=True)
    for name in PERSONA_FILES:
        (directory / name).write_bytes((PERSONA_DIR / name).read_bytes())
    return [directory / name for name in PERSONA_FILES]


def settings_summary(settings: Settings) -> dict[str, object]:
    # Model IDs and tunables only; the API key and owner name are deliberately left out.
    return {
        "Classifier model": settings.classifier_model,
        "Generation model": settings.generation_model,
        "Reasoning effort (classifier/generation)": (
            f"{settings.classifier_reasoning_effort}/{settings.generation_reasoning_effort}"
        ),
        "Embedding model": settings.embedding_model,
        "SIMILARITY_THRESHOLD": settings.similarity_threshold,
        "TOP_K": settings.top_k,
        "Chunking (size/overlap)": f"{settings.chunk_size_tokens}/{settings.chunk_overlap_tokens}",
        "Groundedness check": settings.enable_groundedness_check,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="evals.run_eval", description=__doc__)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--repeats", type=int, default=1)
    parser.add_argument("--kb", choices=["synthetic", "real"], default="synthetic")
    parser.add_argument("--yes", action="store_true", help="Skip the confirmation prompt.")
    parser.add_argument("--report-dir", type=Path, default=REPORT_DIR)
    return parser


def _confirm(prompt: str) -> bool:
    return input(prompt).strip().lower() in ("y", "yes")


def main(
    argv: list[str] | None = None,
    *,
    settings_loader: Callable[[], Settings] = load_settings,
    services_builder: Callable[[Settings], Services] = build_services,
    confirm: Callable[[str], bool] = _confirm,
) -> int:
    args = build_parser().parse_args(argv)
    if args.repeats < 1:
        print("--repeats must be at least 1.", file=sys.stderr)
        return 2
    if args.kb == "real" and args.dataset.resolve() == DEFAULT_DATASET.resolve():
        print(
            f"--kb real needs your own questions: pass --dataset {PERSONAL_DATASET}.",
            file=sys.stderr,
        )
        return 2

    try:
        cases = load_cases(args.dataset)
        settings = settings_loader()
    except (DatasetError, ConfigError) as exc:
        print(exc, file=sys.stderr)
        return 1

    low, high = estimate_calls(len(cases), args.repeats, settings.enable_groundedness_check)
    print(f"{len(cases)} questions x {args.repeats} repeat(s), `{args.kb}` knowledge base.")
    print(f"Estimated OpenAI calls: {low} to {high} (plus embedding calls to ingest the persona).")
    if not args.yes and not confirm("This uses your API key and costs money. Continue? [y/N] "):
        print("Aborted.")
        return 1

    if args.kb == "synthetic":
        with tempfile.TemporaryDirectory(prefix="personal-rag-eval-") as tmp:
            # A throwaway data dir: the real ./data index is never opened by a synthetic run.
            temp_settings = settings.model_copy(update={"data_dir": Path(tmp) / "data"})
            if temp_settings.data_dir.resolve() == settings.data_dir.resolve():
                print("Refusing to run: temporary data dir equals DATA_DIR.", file=sys.stderr)
                return 1
            persona_dir = Path(tmp) / "persona"
            return _evaluate(args, cases, temp_settings, services_builder, persona_dir)
    return _evaluate(args, cases, settings, services_builder, persona_dir=None)


def _evaluate(
    args: argparse.Namespace,
    cases: list[EvalCase],
    settings: Settings,
    services_builder: Callable[[Settings], Services],
    persona_dir: Path | None,
) -> int:
    services = services_builder(settings)
    ingest_tokens = 0
    if persona_dir is not None:
        for path in prepare_persona(persona_dir):
            result = services.ingestion.ingest(path.name, path.read_bytes())
            print(f"ingested {result.filename}: {result.status}, {result.chunk_count} chunks")
        ingest_tokens = services.embedder.tokens_used
    elif services.store.is_empty():
        print("The real knowledge base is empty. Ingest your documents first.", file=sys.stderr)
        return 1

    try:
        runs = run_cases(cases, services.pipeline, args.repeats, progress=print)
    except (IndexMismatchError, UpstreamError) as exc:
        print(f"Eval aborted: {exc}", file=sys.stderr)
        return 1

    meta = RunMeta(
        timestamp=datetime.now(),
        dataset=str(args.dataset),
        kb=args.kb,
        repeats=args.repeats,
        settings=settings_summary(settings),
        ingest_embedding_tokens=ingest_tokens,
    )
    args.report_dir.mkdir(parents=True, exist_ok=True)
    report_path = args.report_dir / f"{meta.timestamp:%Y%m%d-%H%M%S}.md"
    report_path.write_text(render_report(runs, meta), encoding="utf-8")

    print("\n" + render_summary(runs, meta))
    print(f"\nFull report: {report_path}")
    errored = metrics.error_rate(runs)
    if errored.hits:
        print(
            f"WARNING: {errored} runs ended in `error` or `invalid_input`. Check the API key, "
            "model IDs and network before trusting these metrics.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
